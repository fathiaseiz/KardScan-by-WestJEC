// Helper to generate realistic Meishi SVG cards
function createCustomCardSvg(opts: {
  bg: string;
  accent: string;
  textColor: string;
  subColor: string;
  company: string;
  subCompany?: string;
  name: string;
  subName?: string;
  role: string;
  address: string;
  phone: string;
  email: string;
  website: string;
}): string {
  const isDark = opts.bg.startsWith('#0') || opts.bg.startsWith('#1');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="360" viewBox="0 0 600 360">
    <rect width="600" height="360" rx="12" fill="${opts.bg}"/>
    <rect x="0" y="0" width="8" height="360" fill="${opts.accent}"/>
    <!-- Accent geometry -->
    <circle cx="540" cy="50" r="80" fill="none" stroke="${opts.accent}" stroke-width="1.5" opacity="${isDark ? '0.3' : '0.15'}"/>
    <!-- Company Logo & Name -->
    <g transform="translate(48, 45)">
      <rect x="0" y="0" width="26" height="26" rx="5" fill="${opts.accent}"/>
      <text x="36" y="19" font-family="'Noto Sans JP', sans-serif" font-size="16" font-weight="700" fill="${opts.textColor}">${opts.company}</text>
      ${opts.subCompany ? `<text x="36" y="34" font-family="sans-serif" font-size="10" fill="${opts.subColor}">${opts.subCompany}</text>` : ''}
    </g>
    <!-- Role & Person Name -->
    <g transform="translate(48, 145)">
      <text x="0" y="0" font-family="'Noto Sans JP', sans-serif" font-size="12" font-weight="600" fill="${opts.accent}">${opts.role}</text>
      <text x="0" y="36" font-family="'Noto Sans JP', 'Noto Serif JP', serif" font-size="28" font-weight="700" fill="${opts.textColor}">${opts.name}</text>
      ${opts.subName ? `<text x="0" y="56" font-family="sans-serif" font-size="11" fill="${opts.subColor}">${opts.subName}</text>` : ''}
    </g>
    <!-- Divider -->
    <line x1="48" y1="235" x2="552" y2="235" stroke="${isDark ? '#334155' : '#E2E8F0'}" stroke-width="1"/>
    <!-- Contact Info -->
    <g transform="translate(48, 258)" font-family="'Noto Sans JP', sans-serif" font-size="10.5" fill="${opts.subColor}">
      <text x="0" y="0">${opts.address}</text>
      <text x="0" y="19">TEL: ${opts.phone}</text>
      <text x="0" y="38" fill="${opts.accent}">E-mail: ${opts.email}</text>
      <text x="0" y="57">${opts.website}</text>
    </g>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

